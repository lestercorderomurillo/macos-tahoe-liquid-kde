#!/usr/bin/env python3
"""Export original Apple symbol contours from the already bundled SF Pro font.

FontTools is needed only to regenerate the committed native paths. The desktop
plugin uses QtGui alone and has no font or SVG-loader dependency for its icons.
"""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / 'src/offline/fonts/SF-Pro-Display-Regular.otf'
DESTINATION = ROOT / 'src/offline/plasmoids/org.kde.mac.tahoe.liquid.globalmenu'
# Glyph identity and menu bounds measured from the real 2x Tahoe reference.
SYMBOLS = {
    'computer': ('laptopcomputer', 'uni1007DB.small', 15, 9),
    'preferences-system': ('gear', 'uni10035F.small', 11.5, 11.5),
    'dialog-cancel': ('xmark.octagon', 'uni100489.small', 11, 10.5),
    'system-suspend': ('macOS Sleep', 'uni10071A.small', 10.5, 10.5),
    'system-reboot': ('macOS Restart', 'uni100BC6.small', 8, 9),
    'system-shutdown': ('power', 'uni1001A8.small', 10.5, 11),
    'system-lock-screen': ('lock', 'uni1003A0.small', 7.5, 10.5),
    'user-identity': ('person.crop.circle', 'uni10026D.small', 10.5, 10.5),
}


def main():
    from fontTools.ttLib import TTFont
    from fontTools.pens.basePen import BasePen
    from fontTools.pens.boundsPen import BoundsPen
    from fontTools.pens.transformPen import TransformPen

    font = TTFont(FONT)
    glyphs = font.getGlyphSet()
    lines = [
        '// Original Apple glyph outlines; copyright Apple Inc., as recorded in the bundled font.',
        '// Generated by src/scripts/build_menu_symbols.py; do not redraw these contours.',
        '#pragma once', '#include <QPainterPath>', '#include <QString>',
        'namespace SystemMenuSymbols {',
        'inline QPainterPath path(const QString& name) {',
        '    QPainterPath p;', '    p.setFillRule(Qt::WindingFill);',
    ]

    class NativePen(BasePen):
        def emit(self, method, *points):
            values = ', '.join(f'{value:.5f}'.rstrip('0').rstrip('.') or '0'
                               for point in points for value in point)
            lines.append(f'        p.{method}({values});')
        def _moveTo(self, point): self.emit('moveTo', point)
        def _lineTo(self, point): self.emit('lineTo', point)
        def _curveToOne(self, a, b, c): self.emit('cubicTo', a, b, c)
        def _qCurveToOne(self, a, b): self.emit('quadTo', a, b)
        def _closePath(self): lines.append('        p.closeSubpath();')
        def _endPath(self): pass

    for index, (name, (symbol, glyph, width, height)) in enumerate(SYMBOLS.items()):
        bounds = BoundsPen(glyphs)
        glyphs[glyph].draw(bounds)
        left, bottom, right, top = bounds.bounds
        scale = min(width / (right - left), height / (top - bottom))
        transform = (scale, 0, 0, -scale,
                     8 - scale * (left + right) / 2,
                     8 + scale * (bottom + top) / 2)
        lines.append(f'    {"if" if index == 0 else "else if"} (name == QLatin1String("{name}")) {{ // {symbol}: {glyph}')
        glyphs[glyph].draw(TransformPen(NativePen(glyphs), transform))
        lines.append('    }')
    lines += ['    return p;', '}', '} // namespace SystemMenuSymbols', '']
    header = '\n'.join(lines)
    (DESTINATION / 'systemmenusymbols.h').write_text(header)
    provenance = {
        'font': str(FONT.relative_to(ROOT)),
        'font_sha256': hashlib.sha256(FONT.read_bytes()).hexdigest(),
        'font_copyright': '© 2015-2020 Apple Inc. All rights reserved.',
        'generator': 'src/scripts/build_menu_symbols.py',
        'transform': 'Original contours only; uniform scaling and translation into the 16px menu cell; no tracing or hand reconstruction.',
        'coordinate_precision': 0.00001,
        'reference_images': [
            'https://media.512pixels.net/downloads/macos-screenshots/26/26-Tahoe-About-This-Mac-Menu.png',
            'https://media.512pixels.net/downloads/macos-screenshots/27/27-Golden-Gate-About-This-Mac-Menu.png',
        ],
        'symbols': {name: {'symbol': symbol, 'glyph': glyph, 'tahoe_bounds': [width, height]}
                    for name, (symbol, glyph, width, height) in SYMBOLS.items()},
        'golden_gate': 'Same original laptop and gear contours; gear uses the 24px reference size instead of Tahoe\'s 23px at 2x. Other non-featured symbols are hidden.',
        'app_store': 'Existing approved drawing retained unchanged at user request.',
    }
    (DESTINATION / 'systemmenusymbols.json').write_text(json.dumps(provenance, indent=2) + '\n')


if __name__ == '__main__':
    main()
