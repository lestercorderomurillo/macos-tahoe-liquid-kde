"""Rebuild the bundled German and Brazilian Portuguese KDE catalogs.

Run with Python from any directory; gettext's msgfmt must be on PATH.
The JSON catalogs are the editable source shared with the installer.
"""

import json
from pathlib import Path
import re
import subprocess
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = ("pt_BR", "de")
KCM_DOMAIN = "kwin_effect_liquidglass"
_STRING = r'"(?:[^"\\]|\\.)*"'
_CALL = re.compile(
    r'\b(i18n|i18nc|i18np|i18ncp|i18nd|i18ndc|i18ndp)\s*\(\s*'
    r'((?:' + _STRING + r'\s*,?\s*)+)')


def widget_messages(widget: Path) -> dict[tuple[str | None, str], str | None]:
    messages = {}
    for path in sorted([*widget.rglob("*.qml"), *widget.rglob("*.js"), *widget.glob("*.cpp")]):
        # The Dock's native backend uses KDE's complete taskmanager domain.
        if path.suffix == ".cpp" and widget.name.endswith("taskmanager"):
            continue
        for match in _CALL.finditer(path.read_text(encoding="utf-8")):
            function = match[1]
            arguments = [json.loads(s) for s in re.findall(_STRING, match[2])]
            if "d" in function:
                if arguments.pop(0) != f"plasma_applet_{widget.name}":
                    continue
            context = arguments.pop(0) if "c" in function else None
            if arguments:
                plural = arguments[1] if function.endswith("p") and len(arguments) > 1 else None
                messages[context, arguments[0]] = plural
    return messages


def kcm_messages() -> dict[tuple[None, str], None]:
    ui = ROOT / "offline/kwin-effects/acrylic-glass/src/kcm/config.ui"
    return {(None, node.text): None for node in ET.parse(ui).iter("string")
            if node.text and node.get("notr") != "true"}


def write_catalog(base: Path, domain: str, messages: dict,
                  language: str, catalog: dict[str, str], locale_dir: Path) -> None:
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    plural_rule = "n > 1" if language == "pt_BR" else "n != 1"
    header = (
        "Project-Id-Version: MacTahoe Liquid KDE\n"
        "PO-Revision-Date: 2026-10-22 00:00-0600\n"
        "Last-Translator: MacTahoe Liquid KDE contributors\n"
        f"Language-Team: {language}\nLanguage: {language}\n"
        "MIME-Version: 1.0\nContent-Type: text/plain; charset=UTF-8\n"
        "Content-Transfer-Encoding: 8bit\n"
        f"Plural-Forms: nplurals=2; plural=({plural_rule});\n")
    lines = ["# Generated by src/scripts/build_translations.py; edit src/scripts/locales/*.json.",
             'msgid ""', "msgstr " + quote(header), ""]
    for (context, message), plural in sorted(messages.items(), key=lambda item: (item[0][0] or "", item[0][1])):
        if context is not None:
            lines.append("msgctxt " + quote(context))
        lines.append("msgid " + quote(message))
        if plural:
            lines.extend(["msgid_plural " + quote(plural),
                          "msgstr[0] " + quote(catalog[message]),
                          "msgstr[1] " + quote(catalog[plural])])
        else:
            lines.append("msgstr " + quote(catalog[message]))
        lines.append("")
    po = base / "po" / f"{language}.po"
    mo = locale_dir / language / "LC_MESSAGES" / f"{domain}.mo"
    po.parent.mkdir(parents=True, exist_ok=True)
    mo.parent.mkdir(parents=True, exist_ok=True)
    po.write_text("\n".join(lines), encoding="utf-8")
    subprocess.run(["msgfmt", "--check", "--check-format", "-o", str(mo), str(po)], check=True)


def main() -> None:
    for language in LANGUAGES:
        catalog = json.loads((ROOT / "scripts/locales" / f"{language}.json").read_text(encoding="utf-8"))
        for widget in sorted((ROOT / "offline/plasmoids").glob("org.kde.mac*")):
            messages = widget_messages(widget)
            if not messages:
                continue
            locales = widget / ("locale" if widget.name.endswith("globalmenu") else "contents/locale")
            write_catalog(widget, f"plasma_applet_{widget.name}", messages, language, catalog, locales)
        effect = ROOT / "offline/kwin-effects/acrylic-glass"
        write_catalog(effect, KCM_DOMAIN, kcm_messages(), language, catalog, effect / "locale")


if __name__ == "__main__":
    main()
